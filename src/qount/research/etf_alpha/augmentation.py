"""CPU-only immutable bootstrap shards. No Torch import or CUDA workers."""
from __future__ import annotations

from concurrent.futures import ProcessPoolExecutor, as_completed
from dataclasses import asdict
import multiprocessing as mp
import os
from pathlib import Path
import sys
import time

import numpy as np

from .artifacts import GUARDS, finish_manifest, read_json, sha256, verify_files, write_json
from .data import total_return_index
from qount.research.etf_trader.scorer import daily_returns
from .expanded_data import BootstrapSpec, block_indices, bootstrap_panel, label_continuity, load_panel, representation
from .features import build_features

_SOURCE = None
_RETURNS = None


def _initialize(source):
    global _SOURCE, _RETURNS
    from threadpoolctl import threadpool_limits
    threadpool_limits(limits=1)
    _SOURCE = load_panel(Path(source))
    _RETURNS = (daily_returns(total_return_index(_SOURCE.close, _SOURCE.dividends, _SOURCE.splits)),
                daily_returns(_SOURCE.cash_close[:, None])[:, 0])


def generate_shard(task):
    spec, fold_index, lower, upper, first, count, root = task
    root = Path(root)
    root.mkdir()
    shapes = {"assets": ((count, spec.training_sessions, 9, 84), np.float32),
              "market": ((count, spec.training_sessions, 17), np.float32),
              "mu20": ((count, spec.training_sessions, 9), np.float32),
              "mask": ((count, spec.training_sessions, 9), np.bool_),
              "source_indices": ((count, spec.sessions), np.int32)}
    arrays = {k: np.lib.format.open_memmap(root / f"{k}.npy", mode="w+", dtype=dtype, shape=shape)
              for k, (shape, dtype) in shapes.items()}
    rows = np.arange(spec.warmup_sessions, spec.warmup_sessions + spec.training_sessions)
    started, usable = time.monotonic(), 0
    for local in range(count):
        index = first + local
        seed = np.random.SeedSequence([spec.seed, fold_index, index])
        indices = block_indices(spec.sessions, lower, upper, spec.block_sessions, seed)
        panel = bootstrap_panel(_SOURCE, indices, source_returns=_RETURNS)
        features = build_features(panel)
        values = representation(features.raw[rows], features.normalized[rows], features.names)
        market = features.market_normalized[rows].astype(np.float32)
        if not features.available[rows].all() or not features.market_available[rows].all():
            raise ValueError("bootstrap warmup has incomplete causal features")
        if not np.isfinite(values).all() or not np.isfinite(market).all():
            raise FloatingPointError("nonfinite bootstrap features")
        target = panel.open[rows + 21] / panel.open[rows + 1] - 1
        mask = np.broadcast_to(label_continuity(indices, rows)[:, None], target.shape)
        arrays["assets"][local], arrays["market"][local] = values, market
        arrays["mu20"][local], arrays["mask"][local] = target, mask
        arrays["source_indices"][local] = indices
        usable += int(mask.any(axis=1).sum())
    for value in arrays.values():
        value.flush()
    del arrays
    receipt = GUARDS | {"first_world": first, "worlds": count, "source_lower": lower, "source_upper_exclusive": upper,
        "validation_or_test_sampled": False, "usable_dates": usable, "seconds": time.monotonic() - started,
        "worker_pid": os.getpid(), "torch_imported": "torch" in sys.modules,
        "files": {p.name: sha256(p) for p in sorted(root.glob("*.npy"))}}
    write_json(root / "receipt.json", receipt)
    return receipt


def bootstrap_identity(spec, data_root, folds, dates):
    """Bind reusable generated bytes to inputs, causal intervals and generator source."""
    modules = ("augmentation.py", "expanded_data.py", "features.py", "data.py")
    source = Path(__file__).parent
    lower = int(np.searchsorted(dates, "2015-01-01"))
    source_hashes = {name: sha256(source / name) for name in modules}
    source_hashes["etf_trader/scorer.py"] = sha256(source.parent / "etf_trader/scorer.py")
    return {"spec": asdict(spec), "source_manifest_sha256": sha256(Path(data_root) / "manifest.json"),
            "numpy_version": np.__version__, "generator_sha256": source_hashes,
            "fold_intervals": [{"fold": f.fold_id, "lower": lower,
                "upper_exclusive": int(np.searchsorted(dates, f.validation_start)) - f.embargo_sessions}
                for f in folds]}


def verify_bootstrap(spec, data_root, folds, dates, out):
    manifest = read_json(out / "manifest.json")
    contract = read_json(out / "contract.json")
    identity = bootstrap_identity(spec, data_root, folds, dates)
    if any(contract.get(k) != v for k, v in identity.items()):
        raise ValueError("bootstrap source, causal intervals or generator differs")
    expected = len(folds) * int(np.ceil(spec.worlds_per_fold / spec.worlds_per_shard))
    if manifest.get("phase") != "cpu_bootstrap_complete" or manifest.get("completed_shards") != expected:
        raise ValueError("a fully published bootstrap dataset is required")
    for key, value in GUARDS.items():
        if manifest.get(key) != value or contract.get(key) != value:
            raise ValueError("bootstrap research contract mismatch")
    verify_files(out, manifest["files"])
    expected_roots = {f"{f.fold_id}/shard_{first:06d}" for f in folds
                      for first in range(0, spec.worlds_per_fold, spec.worlds_per_shard)}
    roots = {str(p.relative_to(out)) for p in out.glob("*/shard_*") if p.is_dir()}
    if roots != expected_roots:
        raise ValueError("bootstrap shard layout differs from registered worlds")
    for root in sorted(expected_roots):
        required = {f"{root}/{name}" for name in ("receipt.json", "assets.npy", "market.npy",
                                                   "mu20.npy", "mask.npy", "source_indices.npy")}
        if not required.issubset(manifest["files"]):
            raise ValueError("bootstrap manifest omits shard bytes")
        path = out / root
        interval = next(i for i in identity["fold_intervals"] if i["fold"] == Path(root).parts[0])
        first = int(Path(root).name.split("_")[1])
        count = min(spec.worlds_per_shard, spec.worlds_per_fold - first)
        receipt = read_json(path / "receipt.json")
        expected_receipt = {"first_world": first, "worlds": count, "source_lower": interval["lower"],
                            "source_upper_exclusive": interval["upper_exclusive"],
                            "validation_or_test_sampled": False, "torch_imported": False}
        if any(receipt.get(k) != v for k, v in expected_receipt.items()):
            raise ValueError("bootstrap receipt violates past-only CPU generation")
        for name, shape, dtype in (("assets", (count, spec.training_sessions, 9, 84), np.float32),
                ("market", (count, spec.training_sessions, 17), np.float32),
                ("mu20", (count, spec.training_sessions, 9), np.float32),
                ("mask", (count, spec.training_sessions, 9), np.bool_),
                ("source_indices", (count, spec.sessions), np.int32)):
            array = np.load(path / f"{name}.npy", mmap_mode="r", allow_pickle=False)
            if array.shape != shape or array.dtype != dtype:
                raise ValueError("bootstrap resident tensor layout differs")
    return manifest


def prepare_bootstrap(spec: BootstrapSpec, data_root, folds, dates, out, workers, *, expired, emit):
    out.mkdir(exist_ok=True)
    write_json(out / "contract.json", GUARDS | bootstrap_identity(spec, data_root, folds, dates) | {"source": str(data_root),
        "source_start": "2015-01-01", "source_end": "validation_start_minus_5_sessions_exclusive",
        "targets": "next-open TR interval, crossing block joins masked",
        "synthetic_is_new_information": False, "independent_sample_count": "unchanged_real_dates"})
    tasks = []
    lower = int(np.searchsorted(dates, "2015-01-01"))
    for fi, fold in enumerate(folds):
        root = out / fold.fold_id
        root.mkdir()
        upper = int(np.searchsorted(dates, fold.validation_start)) - fold.embargo_sessions
        for first in range(0, spec.worlds_per_fold, spec.worlds_per_shard):
            count = min(spec.worlds_per_shard, spec.worlds_per_fold - first)
            tasks.append((spec, fi, lower, upper, first, count, root / f"shard_{first:06d}"))
    completed, total_dates = 0, 0
    # Forkserver imports only this CPU module in workers, not the CUDA scheduler.
    context = mp.get_context("forkserver")
    mp.set_forkserver_preload([__name__])
    with ProcessPoolExecutor(max_workers=workers, mp_context=context,
                             initializer=_initialize, initargs=(str(data_root),)) as pool:
        futures = {pool.submit(generate_shard, task): task for task in tasks}
        for future in as_completed(futures):
            rec = future.result()
            completed += 1
            total_dates += rec["usable_dates"]
            task = futures[future]
            emit("bootstrap_shard_complete", fold=folds[task[1]].fold_id, first_world=task[4],
                 completed_shards=completed, total_shards=len(tasks), **{k: rec[k] for k in ("seconds", "usable_dates")})
            if expired():
                for pending in futures:
                    pending.cancel()
                raise TimeoutError("CPU preparation reached the global deadline")
    manifest = finish_manifest(out, phase="cpu_bootstrap_complete", spec=asdict(spec),
                               completed_shards=completed, usable_augmented_dates=total_dates,
                               source_is_past_only=True, new_independent_observations=0)
    return manifest
